#!/usr/bin/env node
// 把 tools/dict-builder/packs/base.json 同步进 miniprogram/assets/。
//
// 为什么要拷一份而不是直接引用：小程序的 miniprogramRoot 之外的文件打不进包。
// 和 sync-shared.mjs 同一个理由、同一个做法。
//
// ⚠️ **署名字段（license / licenseUrl / authors）必须原样带过来**，
// 「我的 → 开源许可」页要显示它们。NGSL/BSL 是 CC BY-SA 4.0，署名是许可证义务不是可选项。
//
// ⚠️ 这是 **T1 的临时形态**。T2 做完之后底座词表的权威来源是词鲸的全局只读表，
// 本地这份降级为离线兜底。见 docs/dev-todo.md。

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, '../../../tools/dict-builder/packs/base.json');
const FULL_SRC = resolve(here, '../../../tools/dict-builder/packs/base-full.json');
const JSON_DEST = resolve(here, '../miniprogram/assets/base-words.json');
// 不能放 assets/：微信工具把该目录当静态资源，不会把里面的 TS 注册为逻辑层模块。
const MODULE_DEST = resolve(here, '../miniprogram/services/baseWords.generated.ts');
const PHONETIC_DEST = resolve(here, '../miniprogram/services/basePhonetics.generated.ts');

const pack = JSON.parse(await readFile(SRC, 'utf8'));
const fullPack = JSON.parse(await readFile(FULL_SRC, 'utf8'));

const EXPECTED_SCHEMA = ['spelling', 'band(1-6)', 'sourceBits(1=NGSL,2=BSL)', 'frqRank(0=缺值)'];
if (JSON.stringify(pack.schema) !== JSON.stringify(EXPECTED_SCHEMA)) {
  console.error(
    `[sync-wordpack] ✗ base.json 的 schema 变了：\n  期望 ${JSON.stringify(EXPECTED_SCHEMA)}\n  实际 ${JSON.stringify(pack.schema)}\n` +
      `  packages/shared/src/onboarding.ts 的 BaseWordRow 要跟着改，否则会静默读错列。`
  );
  process.exit(1);
}
for (const k of ['license', 'licenseUrl', 'authors']) {
  if (!pack[k]) {
    console.error(`[sync-wordpack] ✗ base.json 缺少署名字段 ${k}。CC BY-SA 4.0 要求署名，不能发。`);
    process.exit(1);
  }
}

await mkdir(dirname(JSON_DEST), { recursive: true });
const json = JSON.stringify(pack);
await writeFile(JSON_DEST, json, 'utf8');
// 微信小程序运行时不会像 Node 一样把 JSON require 成模块，
// 开发者工具会去找 `base-words.json.js` 并在 S2 直接报模块不存在。
// 同步产出 TS 模块，让词表走小程序正常的 TS -> JS 编译链。
await writeFile(
  MODULE_DEST,
  `// AUTO-GENERATED by scripts/sync-wordpack.mjs. Do not edit.\nconst pack = ${json} as const;\nexport default pack;\n`,
  'utf8',
);

// 列表接口里的旧词可能没有 phonetic。把离线底座的音标单独压成映射作为展示兜底，
// 避免为了一个短字段把完整释义也塞进主包；服务端有值时仍以服务端为准。
const phonetics = Object.fromEntries(
  fullPack.words
    .filter((row) => typeof row[0] === 'string' && typeof row[4] === 'string' && row[4].trim())
    .map((row) => [row[0].toLowerCase(), `/${row[4].replace(/^\/+|\/+$/g, '')}/`]),
);
await writeFile(
  PHONETIC_DEST,
  `// AUTO-GENERATED by scripts/sync-wordpack.mjs. Do not edit.\nconst phonetics: Record<string, string> = ${JSON.stringify(phonetics)};\nexport default phonetics;\n`,
  'utf8',
);

const kb = (JSON.stringify(pack).length / 1024).toFixed(0);
console.log(`[sync-wordpack] base.json → assets/base-words.json + services/baseWords.generated.ts  ${pack.count} 词  ${kb} KB`);
console.log(`[sync-wordpack] base-full.json → services/basePhonetics.generated.ts  ${Object.keys(phonetics).length} 条音标兜底`);
if (kb > 180) console.warn(`[sync-wordpack] ⚠️ ${kb}KB 偏大，主包有 2MB 上限，留意别再往里塞释义`);
