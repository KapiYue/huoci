/** hex → 「family-shade」列表（同一个值可能属于多个族，返回全部）。 */
export function hexToTailwind(hex) {
  const h = hex.toLowerCase();
  const hits = [];
  for (const [family, shades] of Object.entries(TW)) {
    for (const [shade, value] of Object.entries(shades)) {
      if (value === h) hits.push(shade === 'DEFAULT' ? family : `${family}-${shade}`);
    }
  }
  return hits;
}
